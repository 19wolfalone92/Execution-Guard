import assert from "node:assert/strict";

const host="https://execution-guard.19wolf-alone92.workers.dev";
const redirect="https://chatgpt.com/connector_platform_oauth_redirect";
const request=async(path,options={})=>fetch(host+path,{...options,redirect:"manual",signal:AbortSignal.timeout(12000)});
const healthResponse=await request("/health");
assert.equal(healthResponse.status,200,"production health endpoint");
const health=await healthResponse.json();
assert.match(health.version,/^\d+\.\d+\.\d+$/,"production version is reported");
assert.equal(health.status,"online");
assert.equal(health.database,"online");
assert.equal(health.persistence_probe,"verified");
assert.equal(health.oauth?.discovery,"verified");
const clientResponse=await request("/oauth/client-info");
assert.equal(clientResponse.status,200,"registered OAuth client");
const client=await clientResponse.json();
assert.equal(client.status,"ready");
assert.equal(client.redirect_uri,redirect);
assert.equal(client.token_endpoint_auth_method,"none");
const authResponse=await request("/.well-known/oauth-authorization-server");
assert.equal(authResponse.status,200);
const auth=await authResponse.json();
assert.equal(auth.issuer,host);
assert.equal(auth.authorization_endpoint,host+"/authorize");
assert.equal(auth.token_endpoint,host+"/oauth/token");
assert.equal(auth.authorization_response_iss_parameter_supported,true);
assert.ok(auth.code_challenge_methods_supported.includes("S256"));
const resourceResponse=await request("/.well-known/oauth-protected-resource/mcp-private");
assert.equal(resourceResponse.status,200);
const resource=await resourceResponse.json();
assert.equal(resource.resource,host+"/mcp-private");
assert.ok(resource.authorization_servers.includes(host));
const privateResponse=await request("/mcp-private",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({jsonrpc:"2.0",id:1,method:"tools/list"})});
assert.equal(privateResponse.status,401,"private MCP must reject unauthenticated requests");
assert.match(privateResponse.headers.get("WWW-Authenticate")||"",/resource_metadata=/);
console.log("LIVE PRODUCTION SMOKE PASS: production_version="+health.version+", health, D1 persistence, OAuth discovery, registered client and fail-closed MCP.");
